create table if not exists import_log (
  id            bigint generated by default as identity primary key,
  filename      text,
  source        text not null default 'xlsx',
  imported_by   uuid,
  rows_total    int default 0,
  rows_inserted int default 0,
  rows_skipped  int default 0,                 -- дубликаты doc_number = идемпотентность
  period_from   date,
  period_to     date,
  at            timestamptz default now()
);

create table if not exists wash_transactions (
  id              bigint generated by default as identity primary key,
  -- Поправка №1: идемпотентность = источник + внешний ID документа
  source_system   text not null default 'vending_xlsx',   -- vending_xlsx | vending_api | manual
  external_doc_id text not null,                          -- F-CK2502003566
  machine         text not null references machines(id),
  tx_at          timestamptz not null,
  qty            numeric not null default 1,
  amount         numeric not null default 0,
  currency       text not null default 'IDR',
  product        text,
  payment_method text,
  tx_type        text not null default 'sale'
    check (tx_type in ('sale','storage','other')),   -- Sales outbound / Other storage / Other outbound
  wash_kind      text
    check (wash_kind in ('paid','free','coupon')),   -- только для tx_type='sale'
  source         text not null default 'imported'
    check (source in ('live','imported','manual','demo')),
  import_id      bigint references import_log(id) on delete set null,
  created_at     timestamptz default now(),
  constraint wt_source_doc_unique unique (source_system, external_doc_id)
);
create index if not exists wt_machine_at on wash_transactions(machine, tx_at);
create index if not exists wt_at on wash_transactions(tx_at);
create index if not exists wt_kind on wash_transactions(tx_type, wash_kind);

-- Импорт: insert ... on conflict (source_system, external_doc_id) do nothing →
