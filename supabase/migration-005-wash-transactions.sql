-- ─── Разделение платных/промо в агрегатах (§8 ТЗ) ──────────────────
alter table wash_stats add column if not exists w_paid int default 0;
alter table wash_stats add column if not exists w_promo int default 0;
alter table machine_monthly add column if not exists w_paid int default 0;
alter table machine_monthly add column if not exists w_promo int default 0;

-- ─── Пересборка производных агрегатов из транзакций ────────────────
-- Вызывается после каждого импорта (RPC). Security definer: выполняется
-- под правами владельца, política на прямую запись в кэши не нужна.
create or replace function public.refresh_wash_aggregates() returns void
language plpgsql security definer set search_path = public as $$
begin
  -- Помесячно по автоматам
  delete from machine_monthly;
  insert into machine_monthly (machine, month, w, r, w_paid, w_promo)
  select machine, to_char(tx_at, 'YYYY-MM'),
         count(*) filter (where tx_type='sale'),
         coalesce(sum(amount) filter (where tx_type='sale'), 0),
         count(*) filter (where tx_type='sale' and wash_kind='paid'),
         count(*) filter (where tx_type='sale' and wash_kind in ('free','coupon'))
  from wash_transactions group by 1, 2;

  -- Дневная динамика сети: последние 90 дней
  delete from wash_stats;
  insert into wash_stats (d, w, r, w_paid, w_promo)
  select to_char(tx_at::date, 'DD.MM'),
         count(*) filter (where tx_type='sale'),
         coalesce(sum(amount) filter (where tx_type='sale'), 0),
         count(*) filter (where tx_type='sale' and wash_kind='paid'),
         count(*) filter (where tx_type='sale' and wash_kind in ('free','coupon'))
  from wash_transactions
  where tx_at >= now() - interval '90 days'
  group by tx_at::date order by tx_at::date;

  -- Сводка в карточках автоматов (wd/wm/rd/rm/wt/rt/last_wash)
  update machines m set
    wt = coalesce(s.wt, 0), rt = coalesce(s.rt, 0), last_wash = s.last_wash,
    wm = coalesce(s.wm, 0), rm = coalesce(s.rm, 0),
    wd = coalesce(s.wd, 0), rd = coalesce(s.rd, 0)
  from (
    select machine,
      count(*) filter (where tx_type='sale') wt,
      sum(amount) filter (where tx_type='sale') rt,
      max(tx_at::date) filter (where tx_type='sale') last_wash,
      count(*) filter (where tx_type='sale' and tx_at >= now() - interval '30 days') wm,
      coalesce(sum(amount) filter (where tx_type='sale' and tx_at >= now() - interval '30 days'),0) rm,
      count(*) filter (where tx_type='sale' and tx_at::date = current_date) wd,
      coalesce(sum(amount) filter (where tx_type='sale' and tx_at::date = current_date),0) rd
    from wash_transactions group by machine
  ) s where s.machine = m.id;
end $$;

-- RLS (open_access временно, закрытие в 007) + аудит import_log
do $$
declare t text;
begin
  foreach t in array array['wash_transactions','import_log'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "open_access" on %I', t);
    execute format('create policy "open_access" on %I for all using (true) with check (true)', t);
  end loop;
end $$;

notify pgrst, 'reload schema';

