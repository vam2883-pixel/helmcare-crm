-- RLS (временно open, закрытие в 007) + аудит финансовых таблиц и задач
do $$
declare t text;
begin
  foreach t in array array['tasks','task_comments','task_attachments','task_activity',
                           'invoices','payments'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "open_access" on %I', t);
    execute format('create policy "open_access" on %I for all using (true) with check (true)', t);
  end loop;
  foreach t in array array['tasks','invoices','payments'] loop
    execute format('drop trigger if exists audit_%I on %I', t, t);
    execute format('create trigger audit_%I after insert or update or delete on %I
                    for each row execute function public.audit_change()', t, t);
  end loop;
end $$;

notify pgrst, 'reload schema';

